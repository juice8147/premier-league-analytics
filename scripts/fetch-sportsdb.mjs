// Fetches optional club crests and player photos from TheSportsDB and writes
// src/data/sportsdb.generated.ts. Run manually, e.g.:
//   SPORTSDB_KEY=your-key node scripts/fetch-sportsdb.mjs
// Without SPORTSDB_KEY the public test key "123" is used, which is heavily rate limited.
// Players are matched by name within their own club only, so a photo never comes from another squad.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const KEY = process.env.SPORTSDB_KEY || '123'
const BASE = `https://www.thesportsdb.com/api/v1/json/${KEY}`
const SRC_DIR = new URL('../src/data/', import.meta.url)
const OUT_FILE = new URL('../src/data/sportsdb.generated.ts', import.meta.url)
const PREMIER_LEAGUE = 'English Premier League'
// The public test key is limited to a few requests a minute, so space them out.
const DELAY_MS = 4000

const slug = (s) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const fold = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/[^a-z]/g, '')
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function get(endpoint, params = {}, attempt = 1) {
  const url = new URL(`${BASE}/${endpoint}`)
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v)
  await sleep(DELAY_MS)
  const res = await fetch(url)
  // A throttled key can answer 429, or 200 with an empty body. Back off and retry both.
  if (res.status === 429 && attempt < 4) {
    console.log(`Rate limited on ${endpoint}, waiting before retry ${attempt + 1}`)
    await sleep(30_000 * attempt)
    return get(endpoint, params, attempt + 1)
  }
  if (!res.ok) throw new Error(`${endpoint} returned HTTP ${res.status}`)
  const text = (await res.text()).trim()
  if ((text === '' || text === 'null') && attempt < 4) {
    console.log(`No data from ${endpoint}, waiting before retry ${attempt + 1}`)
    await sleep(30_000 * attempt)
    return get(endpoint, params, attempt + 1)
  }
  return text && text !== 'null' ? JSON.parse(text) : {}
}

/** Reads our own club and squad data from the TypeScript sources, so ids match the app exactly. */
function readSquads() {
  const teams = []
  let current = null
  const files = readdirSync(SRC_DIR).filter((f) => /^squads[A-D]\.ts$/.test(f))
  for (const file of files) {
    for (const line of readFileSync(new URL(file, SRC_DIR), 'utf8').split('\n')) {
      const head = line.match(/id: '([^']+)', name: '([^']+)', shortName: '([^']+)'/)
      if (head) {
        current = { id: head[1], name: head[2], shortName: head[3], players: [] }
        teams.push(current)
        continue
      }
      for (const m of line.matchAll(/'(\d+) (\w+) (.+?) ([A-Z]{3}) (\d+)'/g)) {
        current.players.push(m[3])
      }
    }
  }
  return teams
}

const crests = {}
const playerPhotos = {}
const unmatched = []

const ours = readSquads()

// Club names that TheSportsDB spells differently from our data.
const searchName = {
  bournemouth: 'Bournemouth',
  brighton: 'Brighton',
  'nottingham-forest': 'Nottingham Forest',
  'west-ham': 'West Ham',
  wolves: 'Wolverhampton',
}

for (const team of ours) {
  // Search by name, then keep only a Premier League club whose short code matches ours.
  const found = await get('searchteams.php', { t: searchName[team.id] ?? team.name })
  const theirs = (found.teams ?? []).find((t) => t.strLeague === PREMIER_LEAGUE && t.strTeamShort === team.shortName)
  if (!theirs) {
    unmatched.push(`club ${team.id} (${team.shortName}): no Premier League match on TheSportsDB`)
    continue
  }

  const lookup = await get('lookupteam.php', { id: theirs.idTeam })
  const badge = lookup.teams?.[0]?.strBadge
  if (badge) crests[team.id] = badge

  const roster = await get('lookup_all_players.php', { id: theirs.idTeam })
  const byName = new Map()
  for (const p of roster.player ?? []) {
    if (p.strThumb) byName.set(fold(p.strPlayer), p.strThumb)
  }

  for (const name of team.players) {
    const photo = byName.get(fold(name))
    if (photo) playerPhotos[`${team.id}-${slug(name)}`] = photo
    else unmatched.push(`player ${team.id}-${slug(name)}: no photo match for "${name}"`)
  }
}

const body = (record) => JSON.stringify(record, null, 2)
writeFileSync(
  OUT_FILE,
  `// Generated by scripts/fetch-sportsdb.mjs from TheSportsDB. Re-run the script to refresh; do not edit by hand.\n` +
    `export const sportsDbCrests: Record<string, string> = ${body(crests)}\n\n` +
    `export const sportsDbPlayerPhotos: Record<string, string> = ${body(playerPhotos)}\n`,
)

const unmatchedClubs = unmatched.filter((u) => u.startsWith('club'))
console.log(`Crests: ${Object.keys(crests).length} of ${ours.length} clubs`)
console.log(`Player photos: ${Object.keys(playerPhotos).length} of ${ours.reduce((n, t) => n + t.players.length, 0)} players`)
for (const u of unmatchedClubs) console.log(`  ${u}`)
console.log(`Players without a photo match: ${unmatched.length - unmatchedClubs.length}`)
